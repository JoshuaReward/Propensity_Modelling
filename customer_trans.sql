    c.[PublisherID] AS CustomerPublisherID,
    c.[FanID] AS CustomerFanID,
    c.[CustomerGUID],
    c.[CompositeID],
    c.[SourceUID],
    c.[CINID],
    c.[SourceCustomerID],
    c.[AccountType],
    c.[Title],
    c.[City],
    c.[County],
