    s.[ID] AS SchemeTransID,
    s.[SourceID],
    s.[SourceTableID],
    s.[PublisherID] AS SchemePublisherID,
    s.[SubPublisherID],
    s.[NotRewardManaged],
    s.[RetailerID],
    s.[PartnerID],
    s.[OfferID],
    s.[IronOfferID],
    s.[OfferPercentage],
    s.[CommissionRate],
    s.[OutletID],
    s.[FanID] AS SchemeFanID,
    s.[PanID],
    s.[Spend],
    s.[RetailerCashback],
    s.[Investment],
    s.[PublisherCommission],
    s.[RewardCommission],
    s.[VATCommission],
    s.[GrossCommission],
    s.[TranDate],
    s.[TranFixDate],
    s.[TranTime],
    s.[IsNegative],
    s.[IsOnline],
    s.[IsSpendStretch],
    s.[SpendStretchAmount],
