    c.[CurrentlyActive],
    c.[RegistrationDate],
    c.[DeactivatedDate],
    c.[AddedDate] AS CustomerAddedDate,
    c.[ModifiedDate],
    c.[IsCredit],
    c.[IsDebit],
    c.[BrazeUserID],
    p.*,
    t.*,
    o.*
FROM [WH_AllPublishers].[Derived].[SchemeTrans] AS s
INNER JOIN [WH_AllPublishers].[Derived].[Customer] AS c
    ON s.[FanID] = c.[FanID]
inner join wh_allpublishers.derived.partner p on s.[PartnerID] = p.[PartnerID]
inner join wh_allpublishers.derived.publisher t on s.[PublisherID] = t.[PublisherID]
inner join wh_allpublishers.derived.offer o on s.[OfferID] = o.[OfferID]
WHERE s.[TranDate] >= DATEADD(year, -1, CAST(GETDATE() AS date));